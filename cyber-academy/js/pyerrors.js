// تفاصيل أدق حسب نص الرسالة
function refine(type, msg) {
  const m = (re) => msg.match(re);
  if (type === 'NameError' && m(/name '(.+?)' is not defined/)) {
    return [`بايثون ما يعرف الاسم «${m(/name '(.+?)'/)[1]}».`, 'عرّفه أول (مثلاً `x = 5`)، أو راجع تهجئته، أو حطّ النص بين علامتي اقتباس.'];
  }
  if (type === 'TypeError') {
    if (/can only concatenate str/.test(msg) || /must be str, not int/.test(msg)) return ['ما تقدر تجمع نصاً مع رقم بـ `+`.', 'حوّل الرقم لنص بـ `str(رقم)` أو استخدم f-string مثل `f"العمر {age}"`.'];
    if (/unsupported operand type/.test(msg)) return ['العملية بين نوعين ما يتوافقان (مثل نص مع رقم).', 'حوّل القيم لنفس النوع: `int(...)` أو `float(...)` أو `str(...)`.'];
    if (/not subscriptable/.test(msg)) return ['حاولت تستخدم `[ ]` على شي ما يدعمها.', 'تأكد أن المتغير قائمة أو نص أو قاموس.'];
    if (/not callable/.test(msg)) return ['حاولت تستدعي شي كأنه دالة بـ `( )` وهو ليس دالة.', 'ممكن سميت متغيراً باسم دالة، أو حطيت `( )` بعد قيمة.'];
    if (/missing \d+ required positional argument/.test(msg)) return ['استدعيت الدالة وناقصها قيم.', 'عدد القيم عند الاستدعاء لازم يطابق عدد المعاملات.'];
    if (/takes \d+ positional argument/.test(msg)) return ['عدد القيم اللي مررتها للدالة أكثر أو أقل من المطلوب.', 'راجع تعريف الدالة وعدد معاملاتها.'];
    if (/not iterable/.test(msg)) return ['حاولت تدور (loop) على شي مو قابل للتكرار.', 'استخدم `range()` للأرقام، أو تأكد أنه قائمة/نص.'];
  }
  if (type === 'ValueError') {
    if (/invalid literal for int/.test(msg)) return ['حاولت تحوّل نصاً غير رقمي لرقم بـ `int()`.', 'تأكد أن النص أرقام فقط، بدون حروف أو مسافات زايدة. استخدم `.strip()` أحياناً.'];
    if (/could not convert string to float/.test(msg)) return ['حاولت تحوّل نصاً غير رقمي لرقم عشري.', 'تأكد أن النص رقم صحيح مثل `3.5`.'];
    if (/not enough values|too many values/.test(msg)) return ['عدد القيم ما يطابق عدد المتغيرات.', 'تأكد أن عدد المتغيرات على اليسار يساوي عدد القيم على اليمين.'];
  }
  if (type === 'SyntaxError') {
    if (/was never closed/.test(msg)) return ['فيه قوس أو أقواس ما انقفلت.', 'تأكد أن كل `(` لها `)` وكل `[` لها `]` وكل `{` لها `}`.'];
    if (/expected ':'/.test(msg)) return ['ناقص نقطتين `:` في آخر السطر.', 'جمل `if` و`for` و`while` و`def` لازم تنتهي بـ `:`.'];
    if (/unterminated string literal|unterminated triple/.test(msg)) return ['النص ما انقفل بعلامة اقتباس.', 'تأكد أن النص يبدأ وينتهي بنفس نوع علامة الاقتباس.'];
    if (/cannot assign|invalid assignment|Maybe you meant '=='/.test(msg)) return ['استخدمت `=` (تعيين قيمة) وأنت تقصد المقارنة.', 'للمقارنة اكتب `==` وللتعيين `=`.'];
    if (/perhaps you forgot a comma/.test(msg)) return ['ناقص فاصلة `,` بين العناصر.', 'افصل بين العناصر بفاصلة.'];
    if (/Missing parentheses/.test(msg)) return ['`print` لازم يكون بأقواس.', 'اكتب `print("...")`.'];
    if (/invalid character|invalid non-printable/.test(msg)) return ['فيه حرف غير مسموح بالكود (غالباً علامة اقتباس منحنية “ ” أو مسافة مخفية).', 'امسح السطر واكتبه من جديد بعلامات اقتباس عادية `"`.'];
  }
  if (type === 'IndentationError') {
    if (/expected an indented block/.test(msg)) return ['بعد النقطتين `:` لازم يجي سطر مزاح.', 'اكتب السطر التالي بإزاحة 4 مسافات (زر Tab).'];
    if (/unexpected indent/.test(msg)) return ['سطر مزاح بدون سبب.', 'شيل المسافات الزايدة من أول السطر.'];
    if (/unindent does not match/.test(msg)) return ['إزاحة السطر ما تطابق أي كتلة سابقة.', 'اجعل كل أسطر الكتلة بنفس عدد المسافات.'];
  }
  return T[type] || ['صار خطأ غير متوقع في الكود.', 'اقرأ رسالة الخطأ بالإنجليزي وركّز على رقم السطر.'];
}

// HTML جاهز للعرض (كل النصوص مهرّبة)
export function explain(err) {
  if (!err) return '';
  const [meaning, fix] = refine(err.type, err.msg || '');
  const bt = (s) => esc(s).replace(/`(.+?)`/g, '<code class="en">$1</code>');
  return `<div class="pyerr">
    <b>🔴 ${err.line ? `خطأ في السطر ${err.line}` : 'خطأ'}</b>
    ${err.text ? `<pre class="code" dir="ltr">${esc(err.text)}</pre>` : ''}
    <div class="en muted" style="margin-bottom:6px">${esc(err.type)}: ${esc(err.msg)}</div>
    <p><b>وش معناه؟</b> ${bt(meaning)}</p>
    <p><b>كيف تصلحه؟</b> ${bt(fix)}</p>
  </div>`;
}

